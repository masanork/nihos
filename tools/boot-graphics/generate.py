#!/usr/bin/env python3
"""Bake the fixed boot inscription into 4-bit RLE masks (Pillow required).

The target does not load a font, allocate memory, or read a filesystem.
See src/graphics/boot/README.md for the pinned font and its license.
"""
import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
# Old-form glyphs are a display treatment of the supplied transcription,
# not a diplomatic transcription of any one manuscript (see boot/README.md).
POEM = ("墨之江之", "岸野之榛丹", "丹穗所經迹", "丹穗葉寐我八", "丹穗氷而將居")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    masks = bytearray()
    sprites = []
    layout = "portrait"
    cache = {}

    def text(value, size, x, y, ink="normal", group=0, status=0):
        font = ImageFont.truetype(str(args.font), size)
        bounds = font.getbbox(value)
        image = Image.new("L", (bounds[2] - bounds[0], bounds[3] - bounds[1]))
        ImageDraw.Draw(image).text((-bounds[0], -bounds[1]), value, font=font, fill=255)
        pixels = [(v * 15 + 127) // 255 for v in image.tobytes()]
        offset = len(masks)
        i = 0
        while i < len(pixels):
            count = 1
            while count < 16 and i + count < len(pixels) and pixels[i + count] == pixels[i]:
                count += 1
            masks.append((pixels[i] << 4) | (count - 1))
            i += count
        length = len(masks) - offset
        key = (value, size)
        if key in cache:
            del masks[offset:]
            offset, length = cache[key]
        else:
            cache[key] = (offset, length)
        sprites.append((x, y, image.width, image.height, offset, length, ink, group, status, layout))

    text("nihos", 104, 86, 170)
    text("にほす ─ 色づける", 25, 92, 288, "muted")
    # Classical Japanese reads downwards, with columns ordered right to left.
    for column, line in enumerate(POEM):
        for row, character in enumerate(line):
            highlighted = column >= 2 and row < 2
            text(character, 45, 520 - column * 88, 456 + row * 65,
                 "dye" if highlighted else "normal", column - 2 if highlighted else 0)
    text("萬葉集　卷十六・三八〇一", 20, 238, 910, "muted")
    text("素のハードウェアを、色づける。", 26, 92, 1038)
    text("BOOT / DISPLAY", 18, 112, 1160, "muted", status=1)
    text("BOOT / MEMORY", 18, 112, 1160, "muted", status=2)
    text("BOOT / CORES", 18, 112, 1160, "muted", status=3)
    text("BOOT / INPUT", 18, 112, 1160, "muted", status=4)
    text("BOOT / READY", 18, 112, 1160, "muted", status=5)
    text("BOOT / FAILED - SEE SERIAL", 18, 112, 1160, "error", status=6)
    # Landscape is a new composition, keeping the poem's vertical reading order.
    layout = "landscape"
    text("nihos", 104, 96, 211)
    text("にほす ─ 色づける", 25, 102, 330, "muted")
    text("素のハードウェアを、色づける。", 22, 102, 472)
    for column, line in enumerate(POEM):
        for row, character in enumerate(line):
            highlighted = column >= 2 and row < 2
            text(character, 40, 1110 - column * 82, 154 + row * 56,
                 "dye" if highlighted else "normal", column - 2 if highlighted else 0)
    text("萬葉集　卷十六・三八〇一", 18, 814, 536, "muted")
    for state, label in enumerate(("DISPLAY", "MEMORY", "CORES", "INPUT", "READY", "FAILED - SEE SERIAL"), 1):
        text("BOOT / " + label, 18, 122, 641, "error" if state == 6 else "muted", status=state)
    destination = ROOT / "src/graphics/boot"
    (destination / "masks.rle").write_bytes(masks)
    declarations = [
        "// Generated by tools/boot-graphics/generate.py; do not edit.",
        "// Noto Serif CJK JP Regular; SIL OFL 1.1 (see OFL.txt).",
        "// Copyright 2017-2024 Adobe (http://www.adobe.com/).",
        f"// Font SHA256: {hashlib.sha256(args.font.read_bytes()).hexdigest()}",
        "pub const Layout = enum { portrait, landscape };",
        "pub const Ink = enum { normal, muted, dye, @\"error\" };",
        "pub const Sprite = struct { x: u16, y: u16, width: u16, height: u16, offset: u32, length: u32, ink: Ink, group: u8, status: u8, layout: Layout };",
        'pub const masks = @embedFile("masks.rle");',
        "pub const sprites = [_]Sprite{",
    ]
    for x, y, width, height, offset, length, ink, group, status, layout in sprites:
        ink = '@"error"' if ink == "error" else ink
        declarations.append(
            f"    .{{ .x = {x}, .y = {y}, .width = {width}, .height = {height}, "
            f".offset = {offset}, .length = {length}, .ink = .{ink}, .group = {group}, .status = {status}, .layout = .{layout} }},"
        )
    declarations.append("};\n")
    (destination / "assets.zig").write_text("\n".join(declarations))
    print(f"{len(sprites)} masks, {len(masks):,} bytes; poem: {''.join(POEM)}")


if __name__ == "__main__":
    main()
