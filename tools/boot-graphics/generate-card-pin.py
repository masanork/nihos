#!/usr/bin/env python3
"""Bake fixed PIN-screen lettering from the same pinned OFL font as boot."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT_SHA = "d9854c7a8ef170b5a7932558856fd64eb8de0b007cd823fed6f9f514ad2803d3"
LABELS = [("title", "券面事項入力補助", 36), ("instruction", "入力補助用の暗証番号", 28),
          ("privacy", "暗証番号は保存しません", 22), ("remaining", "残り", 24),
          ("times", "回", 24), ("unknown", "不明", 24),
          ("disabled", "入力は無効です", 24), ("cancel", "中止", 30),
          ("erase", "消す", 30), ("submit", "読み取る", 34)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != FONT_SHA:
        parser.error("font differs from the pinned Noto Serif CJK JP Regular")
    masks = bytearray()
    labels = LABELS + [(f"d{i}", str(i), 52) for i in range(10)]
    declarations = ["// Generated by generate-card-pin.py; Noto Serif CJK JP Regular.",
                    "// Copyright 2017-2024 Adobe; SIL OFL 1.1: boot/OFL.txt.",
                    "pub const Id = enum { " + ", ".join(key for key, _, _ in labels) + " };",
                    "pub const Glyph = struct { width: u16, height: u16, offset: u32, length: u32 };",
                    'pub const masks = @embedFile("card_pin.rle");', "pub const glyphs = [_]Glyph{"]
    for _, text, size in labels:
        font = ImageFont.truetype(str(args.font), size)
        x0, y0, x1, y1 = font.getbbox(text)
        image = Image.new("L", (x1 - x0, y1 - y0))
        ImageDraw.Draw(image).text((-x0, -y0), text, font=font, fill=255)
        pixels = [(value * 15 + 127) // 255 for value in image.tobytes()]
        offset = len(masks)
        i = 0
        while i < len(pixels):
            run = 1
            while run < 16 and i + run < len(pixels) and pixels[i + run] == pixels[i]:
                run += 1
            masks.append(pixels[i] << 4 | (run - 1))
            i += run
        declarations.append(f"    .{{ .width = {image.width}, .height = {image.height}, .offset = {offset}, .length = {len(masks) - offset} }},")
    declarations.append("};\n")
    (ROOT / "src/graphics/card_pin_assets.zig").write_text("\n".join(declarations))
    (ROOT / "src/graphics/card_pin.rle").write_bytes(masks)
    print(f"{len(labels)} masks, {len(masks)} bytes")


if __name__ == "__main__":
    main()
