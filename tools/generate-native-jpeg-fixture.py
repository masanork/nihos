#!/usr/bin/env python3
"""Generate fixed 720p/Q75/4:2:2 JPEG header and natural-order quantizers.

Pillow supplies baseline standard Huffman tables; only the header is embedded.
The device JPEG accelerator must generate the entire entropy-coded payload.
"""
import io
from pathlib import Path
from PIL import Image

out = io.BytesIO()
Image.new('RGB', (1280, 720)).save(out, 'JPEG', quality=75, subsampling=1, optimize=False)
data = out.getvalue()
offset = 2
while data[offset:offset + 2] != b'\xff\xda':
    length = int.from_bytes(data[offset + 2:offset + 4], 'big')
    offset += length + 2
end = offset + 2 + int.from_bytes(data[offset + 2:offset + 4], 'big')
padding = (-(end + 4)) % 64
header = data[:offset] + b'\xff\xfe' + (padding + 2).to_bytes(2, 'big') + bytes(padding) + data[offset:end]
assert len(header) % 64 == 0
tables = Image.open(io.BytesIO(data)).quantization
lines = ['/* Generated by tools/generate-native-jpeg-fixture.py; baseline Q75, 1280x720, 4:2:2. */']
for name, ctype, values in [('jpeg_header', 'uint8_t', header), ('jpeg_quant_y', 'uint32_t', tables[0]), ('jpeg_quant_c', 'uint32_t', tables[1])]:
    lines.append(f'static const {ctype} {name}[] __attribute__((section(".flash.rodata.records"))) = {{')
    for i in range(0, len(values), 16):
        lines.append('    ' + ','.join(str(v) for v in values[i:i+16]) + ',')
    lines.append('};')
Path(__file__).resolve().parents[1].joinpath('src/board/tab5/native_jpeg_tables.h').write_text('\n'.join(lines) + '\n')
print('Fixed JPEG header bytes:', len(header))
