#!/usr/bin/env python3
"""Bake bounded TTB/LTR font masks with the pinned FT/HB host renderer."""
import argparse
import hashlib
import io
import json
import shutil
import subprocess
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PINS = {'BIZUDGothic-Regular.ttf': '7d2b48d84ef4e65c9f85bcf65fb1fb41c92b134be641fab6a7141d597c9a92b0',
        'BIZUDMincho-Regular.ttf': '468ee6d9b149ca144809e03841bf18740ecf014e055a00da6ecaf1aaf4165af2'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--probe', type=Path, required=True)
    parser.add_argument('--renderer', type=Path, required=True)
    args = parser.parse_args()
    fonts = args.probe / 'sources'
    for name, sha in PINS.items():
        if hashlib.sha256((fonts / name).read_bytes()).hexdigest() != sha:
            raise SystemExit('font digest mismatch: ' + name)
    output = bytearray()
    glyphs, placements, cache = [], [], {}

    def add(value, size, x, y, color, mincho=False, vertical=False, centered=False):
        key = (value, size, mincho, vertical)
        if key not in cache:
            font = 'BIZUDMincho-Regular.ttf' if mincho else 'BIZUDGothic-Regular.ttf'
            raw = subprocess.check_output([str(args.renderer), str(fonts / font), str(size), 'ttb' if vertical else 'ltr', value])
            mask = Image.open(io.BytesIO(raw)).convert('L')
            levels = [(v + 8) // 17 for v in mask.tobytes()]
            offset = len(output)
            at = 0
            while at < len(levels):
                end = at + 1
                while end < len(levels) and levels[end] == levels[at] and end - at < 16:
                    end += 1
                output.append((levels[at] << 4) | (end - at - 1))
                at = end
            cache[key] = len(glyphs)
            glyphs.append({'text': value, 'pixels': size, 'vertical': vertical, 'width': mask.width,
                           'height': mask.height, 'offset': offset, 'length': len(output) - offset})
        index = cache[key]
        if centered:
            x -= glyphs[index]['width'] // 2
        if not (0 <= x and 0 <= y and x + glyphs[index]['width'] <= 720 and y + glyphs[index]['height'] <= 1280):
            raise ValueError('placement outside frame: ' + value)
        placements.append((index, x, y, color))

    add('NIHOS  /  CARD READER', 18, 52, 68, 0xbec7be)
    add('丹穂', 108, 82, 304, 0xd4795e, True, True)
    add('にほす', 19, 72, 571, 0xb8bfb4)
    for column, line in enumerate(('墨之江之', '岸野之榛丹', '丹穂所経迹', '丹穂葉寐我八', '丹穂氷而将居')):
        for row, char in enumerate(line):
            add(char, 36, 602 - column * 74, 294 + row * 60,
                0xd4795e if column >= 2 and row < 2 else 0xe5e8dc, True, True, True)
    add('万葉集　巻十六・三八〇一', 17, 292, 806, 0xa1aca3)
    add('素のハードウェアを、色づける。', 26, 56, 982, 0xe5e8dc)
    add('カード機能を準備しています', 21, 87, 1132, 0xb8bfb4)
    directory = ROOT / 'src/graphics/card_boot'
    directory.mkdir(exist_ok=True)
    (directory / 'masks.rle').write_bytes(output)
    source = ['// Generated by tools/design/card-splash-assets.py. Pinned BIZ UD / SIL OFL 1.1.',
              'pub const Mask = struct { width: u16, height: u16, offset: u32, length: u32 };',
              'pub const Placement = struct { mask: u16, x: u16, y: u16, color: u32 };',
              'pub const masks = @embedFile("masks.rle");', 'pub const glyphs = [_]Mask{']
    for glyph in glyphs:
        source.append('    .{ .width = %d, .height = %d, .offset = %d, .length = %d },' % tuple(glyph[k] for k in ('width', 'height', 'offset', 'length')))
    source += ['};', 'pub const placements = [_]Placement{']
    for index, x, y, color in placements:
        source.append('    .{ .mask = %d, .x = %d, .y = %d, .color = 0x%06x },' % (index, x, y, color))
    source += ['};', '']
    (directory / 'assets.zig').write_text('\n'.join(source))
    for name in ('BIZ-UD-Gothic-OFL.txt', 'BIZ-UD-Mincho-OFL.txt'):
        shutil.copy2(fonts / name, directory / name)
    report = {'fonts': PINS, 'renderer': json.loads(subprocess.check_output([str(args.renderer), '--versions'])),
              'encoding': 'A4 run length; upper nibble coverage, lower nibble count minus one',
              'bytes': len(output), 'sha256': hashlib.sha256(output).hexdigest(), 'glyphs': glyphs,
              'surface_origin': 'fe84f47:src/graphics/surface.zig; blend helper inlined for foreground composition',
              'scope': 'fixed boot text only; not native font-worker integration'}
    (directory / 'manifest.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(f'{len(glyphs)} masks / {len(placements)} placements / {len(output)} bytes')


if __name__ == '__main__':
    main()
