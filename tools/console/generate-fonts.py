#!/usr/bin/env python3
"""Bake pinned console faces at their actual pixel size; no target font engine."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version, features
from font_rle import encode

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / 'src/graphics/ascii'
CELL = (15, 30)
BASELINE = 23

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--jetbrains', type=Path, required=True)
    parser.add_argument('--source-code', type=Path, required=True)
    args = parser.parse_args()
    sources = json.loads((DESTINATION / 'fonts.json').read_text())
    for key, path in (('jetbrains', args.jetbrains), ('source_code', args.source_code)):
        record = sources[key]
        assert hashlib.sha256(path.read_bytes()).hexdigest() == record['sha256'], 'font source differs from pinned file'
        font = ImageFont.truetype(str(path), record['pixel_size'])
        masks = bytearray()
        glyphs = []
        for code in range(32, 127):
            bounds = font.getbbox(chr(code), anchor='ls')
            assert bounds[0] >= 0 and bounds[1] + BASELINE >= 0 and bounds[2] <= CELL[0] and bounds[3] + BASELINE <= CELL[1], (code, bounds)
            image = Image.new('L', CELL)
            ImageDraw.Draw(image).text((0, BASELINE), chr(code), font=font, anchor='ls', fill=255)
            pixels = [(p * 15 + 127) // 255 for p in image.tobytes()]
            offset = len(masks)
            masks.extend(encode(pixels))
            glyphs.append((offset, len(masks) - offset))
        assert len(masks) < 65536
        (DESTINATION / (key + '.rle')).write_bytes(masks)
        lines = ['// Generated by tools/console/generate-fonts.py; see fonts.json and OFL notices.',
                 f'// Pillow {pillow_version}; FreeType {features.version("freetype2")}.',
                 f'pub const cell_width = {CELL[0]};', f'pub const cell_height = {CELL[1]};',
                 f'pub const pixel_size = {record["pixel_size"]};',
                 f'pub const masks = @embedFile("{key}.rle");',
                 'pub const Glyph = extern struct { offset: u16, length: u16 };',
                 'pub const glyphs = [_]Glyph{']
        lines.extend(f'    .{{ .offset = {offset}, .length = {length} }},' for offset, length in glyphs)
        lines.append('};\n')
        (DESTINATION / (key + '.zig')).write_text('\n'.join(lines))
        print(f'{record["name"]}: {record["pixel_size"]} px, {len(glyphs)} ASCII glyphs, {len(masks)} mask bytes')

if __name__ == '__main__':
    main()
