#!/usr/bin/env python3
"""Generate broker admission policy from the checked development budget."""
import argparse
import hashlib
import json
from pathlib import Path

import storage_budget

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/kernel/development_memory.zig'


def render():
    data = storage_budget.PROFILE.read_bytes()
    profile = storage_budget.validate_profile(json.loads(data))
    heap = profile['internal_heap_subdivision_bytes']
    ram = profile['psram_peak_envelope_bytes']
    groups = {
        'kernel': (heap['kernel_and_scheduler'], 0),
        'vfs': (heap['storage_and_vfs_control'], ram['vfs_rpc_io']),
        'store': (0, ram['experimental_store_including_map_and_gc']),
        'sqlite': (0, ram['sqlite_including_wal_index']),
        'network': (heap['network_control_excluding_dma_and_stacks'], ram['wifi_tcpip_tls_http_ai']),
        'ble': (heap['ble_control_excluding_dma_and_stacks'], ram['ble_bulk_and_profiles']),
        'ime': (heap['ime_control'], ram['ime_dictionary_cache_composition_and_learning']),
        'vm': (0, ram['vm_4MiB_payload_with_current_buddy_charge']),
        'display': (0, ram['single_framebuffer_and_display']),
        'editor': (0, ram['editor_project_buffers']),
        'sensor_audio': (0, ram['sensor_audio_logs']),
    }
    internal_backing = profile['sram_budget_bytes']['reusable_internal_heap']
    metadata = heap['allocator_and_fragmentation_allowance']
    internal = internal_backing - metadata
    external = 32 * storage_budget.MIB - ram['boot_allocator_metadata_and_guards']
    storage_budget.require(sum(v[0] for v in groups.values()) + heap['minimum_free_reserve'] == internal,
                           'broker internal ownership does not cover the budget')
    storage_budget.require(sum(v[1] for v in groups.values()) + ram['unassigned_headroom'] == external,
                           'broker external ownership does not cover the budget')
    lines = ['//! Generated by tools/generate_memory_profile.py; edit the JSON budget instead.',
             '//! Target admission policy, not registration of the current physical heaps.',
             'pub const api = @import("memory_broker.zig");',
             f'pub const profile_sha256 = "{hashlib.sha256(data).hexdigest()}";',
             f'pub const internal_backing_bytes = {internal_backing};',
             f'pub const metadata_reserve_bytes = {metadata};',
             f'pub const internal_bytes = {internal};', f'pub const external_bytes = {external};',
             'pub const lease_limit = 64;', 'pub const owner_limit = 16;', 'pub const pin_limit = 32;',
             f'pub const Manager = api.Broker({internal // 4096}, {external // 4096}, lease_limit, owner_limit, pin_limit);',
             'pub const policy: api.Policy = .{',
             f'    .floor = .{{ .internal = {heap["minimum_free_reserve"]}, .external = {ram["unassigned_headroom"]} }},',
             '    .groups = block: {', '        var groups: [api.group_count]api.Limits = @splat(.{});']
    for name, (local, remote) in groups.items():
        lines.append(f'        groups[@backingInt(api.Group.{name})] = .{{ .internal = {local}, .external = {remote} }};')
    lines += ['        break :block groups;', '    },', '    .owner_limits = @splat(1),', '};',
              'comptime {', '    if (@sizeOf(Manager) > metadata_reserve_bytes) @compileError("broker metadata exceeds its reserved backing");', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit('generated broker policy is stale; run tools/generate_memory_profile.py')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
